namespace Interoper.Generator.Tests;

public sealed class CodeWriterTests
{
    [Fact]
    public void WritesAGeneratedCSharpFileWithoutUsings() // R27: its code names other namespaces' types with global::
    {
        var writer = CodeWriter.CSharp("Acme.Maps");
        using (writer.Block("public sealed class Map"))
        {
            writer.Line("public double Zoom { get; set; }");
            writer.Line();
            writer.Line("public static Map Create() =>");
            using (writer.Indent())
            {
                writer.Line("new();");
            }
            using (writer.Block("public string Name => Kind switch", "};"))
            {
                writer.Line("_ => \"map\",");
            }
        }
        Assert.Equal("""
            // <auto-generated/>
            #nullable enable

            namespace Acme.Maps;

            public sealed class Map
            {
                public double Zoom { get; set; }

                public static Map Create() =>
                    new();
                public string Name => Kind switch
                {
                    _ => "map",
                };
            }

            """.ReplaceLineEndings("\n"), writer.ToString());
    }

    [Fact]
    public void AnOpenBlockIsAnError()
    {
        var writer = new CodeWriter();
        writer.Block("class A");
        Assert.Throws<InvalidOperationException>(writer.ToString);
    }
}
