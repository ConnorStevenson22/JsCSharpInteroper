using System.Text;

namespace Interoper.Generator;

/// <summary>Writes generated source a line at a time: four-space indents, LF line ends, a final newline.</summary>
public sealed class CodeWriter
{
    private readonly StringBuilder text = new();
    private int depth;

    /// <summary>A C# file: the generated-code header, the usings in the given order, and a file-scoped namespace.</summary>
    public static CodeWriter CSharp(string ns, params string[] usings)
    {
        var writer = new CodeWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();
        foreach (var name in usings)
        {
            writer.Line($"using {name};");
        }
        if (usings.Length > 0)
        {
            writer.Line();
        }
        writer.Line($"namespace {ns};");
        writer.Line();
        return writer;
    }

    /// <summary>One line at the current indent; an empty line has no indent.</summary>
    public CodeWriter Line(string line = "")
    {
        if (line.Length > 0)
        {
            text.Append(' ', depth * 4).Append(line);
        }
        text.Append('\n');
        return this;
    }

    /// <summary>Indents the lines written until the result is disposed.</summary>
    public IDisposable Indent()
    {
        depth++;
        return new Outdent(() => depth--);
    }

    /// <summary><paramref name="header"/>, then a braced block until the result is disposed, closed by <paramref name="close"/>.</summary>
    public IDisposable Block(string header, string close = "}")
    {
        Line(header).Line("{");
        depth++;
        return new Outdent(() =>
        {
            depth--;
            Line(close);
        });
    }

    public override string ToString() =>
        depth == 0 ? text.ToString() : throw new InvalidOperationException("A block or indent is still open.");

    private sealed class Outdent(Action dispose) : IDisposable
    {
        public void Dispose() => dispose();
    }
}
